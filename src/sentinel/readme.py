"""Generated blocks of the README. Every number on the front page comes from evidence/."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

MARK = "<!-- {name}:start (generated by sentinel readme, do not edit by hand) -->"
END = "<!-- {name}:end -->"
QUALITY = "evidence/data_quality"
METRICS = "evidence/published/metrics.json"
LABELS = {
    "max_lottery": "Lottery stocks (max daily return)",
    "high52": "52 week high anchoring",
    "reversal": "Short-term reversal",
    "realized_skew": "Realized skewness",
}


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}%"


QUALITY_TABLES = ("coverage_by_year", "member_count_reconciliation", "survivorship_sensitivity")


def survivorship(tables: dict[str, pd.DataFrame]) -> str:
    """tables holds the three aggregate tables named in QUALITY_TABLES, read by the CLI."""
    cov = tables["coverage_by_year"]
    rec = tables["member_count_reconciliation"]
    sens = (
        tables["survivorship_sensitivity"]
        .set_index("scenario")["ann_return"]
        .astype(float)
        .to_dict()
    )
    first, last = cov.iloc[0], cov.iloc[-1]
    base = float(sens["baseline_missing_dropped"])
    worst = float(sens["missing_imputed_penalty_0.15"])
    mild = float(sens["missing_imputed_penalty_0.05"])
    lines = [
        "| Year | Index member days | Without a price | Members never priced |",
        "|---|---|---|---|",
    ]
    for _, r in cov.iloc[:: max(1, (len(cov) - 1) // 5)].iterrows():
        lines.append(
            f"| {int(r['year'])} | {int(r['member_days'])} | {pct(r['missing_frac'])} | "
            f"{int(r['members_never_priced'])} |"
        )
    lines += [
        "",
        f"In {int(first['year'])}, {pct(first['missing_frac'], 0)} of index member days have no price "
        f"in the free source; by {int(last['year'])} it is still {pct(last['missing_frac'], 0)}. "
        f"The rebuilt member count is {int(rec['members'].min())} to {int(rec['members'].max())} in "
        f"every one of {len(rec)} months, against a target of 500 with a tolerance of 10, so "
        f"{int((~rec['ok']).sum())} of {len(rec)} months fail the reconciliation. "
        f"[FINDING src={QUALITY}/data_quality_coverage_by_year.csv]",
        "",
        f"What that does to a return: an equal-weight portfolio of the names that do have prices "
        f"earns {pct(base)} a year over the window. Charging the missing names a penalty of 5 or 15 "
        f"percent a year, two assumptions that bracket the problem and are not estimates, lowers it "
        f"to {pct(mild)} or {pct(worst)}. The spread between those is larger than the premium any "
        f"signal here is expected to earn. "
        f"[FINDING src={QUALITY}/data_quality_survivorship_sensitivity.csv]",
    ]
    return "\n".join(lines)


def published(root: Path) -> str:
    m = json.loads((root / METRICS).read_text())
    w = m["window"]
    lines = [
        f"Value-weighted quintile long-short returns, {w['start']} to {w['end']}, "
        f"{next(iter(m['signals'].values()))['n_months']} months. Positive means the locked sign held. "
        f"t-statistics use Newey-West errors with {w['nw_lags']} lags; p-values are one-sided and "
        f"Holm-adjusted across the four signals. [FINDING src={METRICS}]",
        "",
        "| Locked signal | Published counterpart | Return per year | t | Holm p | Verdict | "
        "Before 2005, per year (t) |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r in m["signals"].items():
        c = r["context_before_window"]
        lines.append(
            f"| {LABELS[name]} | {r['published_signal']} | {pct(r['mean_annual'])} | {r['t']:.2f} | "
            f"{r['p_one_sided_holm']:.2f} | **{r['verdict'].capitalize()}** | "
            f"{pct(c['mean_annual'])} ({c['t']:.2f}) |"
        )
    c = m["composite"]
    lines.append(
        f"| Equal-weight composite of the four | | {pct(c['mean_annual'])} | {c['t']:.2f} | "
        f"{c['p_one_sided']:.2f} (unadjusted) | **{c['verdict'].capitalize()}** | |"
    )
    pw = {LABELS[n]: r["power_half_pre_window"] for n, r in m["signals"].items()}
    lo, hi = min(pw.values()), max(pw.values())
    lines += [
        "",
        f"How much these tests could see: if each premium were half its pre-2005 size, about what "
        f"Chen, Lopez-Lira and Zimmermann find survives publication, the chance that the locked test "
        f"confirms it is {pct(lo)} to {pct(hi)} per signal, before the Holm adjustment makes it "
        f"harder. "
        + (
            "So not confirmed here is weak evidence that the premiums are gone: a test this noisy "
            "would usually miss a premium of that size. "
            if hi < 0.5
            else ""
        )
        + f"[FINDING src={METRICS}]",
    ]
    lines += [
        "",
        f"The composite has a Sharpe ratio of {c['sharpe_annual']:.2f} before any trading cost, and "
        f"the four series have a mean pairwise correlation of {c['mean_pairwise_correlation']:.2f}. "
        f"The last column is context, not a test: those years were public long before the signs "
        f"were locked. Disposition overhang and abnormal volume have no published counterpart in "
        f"the release and are not tested. [FINDING src={METRICS}]",
        "",
        "Robustness, return per year (t), reported next to the headline and never used to choose it. "
        "The first column uses equal weights for three signals and value weights for the lottery "
        "signal, whose original paper is value-weighted, so that row repeats the headline:",
        "",
        "| Locked signal | Quintiles, each paper's own weighting | Original paper construction |",
        "|---|---|---|",
    ]
    for name, r in m["signals"].items():
        ew, op = r["robustness"]["quintiles_ew"], r["robustness"]["original_paper"]
        lines.append(
            f"| {LABELS[name]} | {pct(ew['mean_annual'])} ({ew['t']:.2f}) | "
            f"{pct(op['mean_annual'])} ({op['t']:.2f}) |"
        )
    return "\n".join(lines)


def headline(root: Path, tables: dict[str, pd.DataFrame]) -> str:
    m = json.loads((root / METRICS).read_text())
    cov = tables["coverage_by_year"]
    sig = m["signals"]
    confirmed = [n for n, r in sig.items() if r["verdict"] == "confirmed"]
    contradicted = [n for n, r in sig.items() if r["verdict"] == "contradicted"]
    early = [n for n, r in sig.items() if r["context_before_window"]["t"] > 1.96]
    w = m["window"]
    count = {0: "None", len(sig): "All"}.get(len(confirmed), str(len(confirmed)))
    return (
        f"**1. Free stock-level data cannot carry this test.** The first real rebuild of the "
        f"point in time S and P 500 found no price history for "
        f"{pct(float(cov['missing_frac'].iloc[0]), 0)} of index member days in "
        f"{int(cov['year'].iloc[0])}, because the free source drops companies that were acquired, "
        f"went bankrupt or were delisted. Those are the stocks behavioral signals bet on, so the "
        f"gate on stock-level results stays shut. [FINDING src={QUALITY}/data_quality_coverage_by_year.csv]\n\n"
        f"**2. On data without that hole, the locked signs do not hold up.** Tested on published "
        f"portfolios built from the full CRSP universe, {w['start']} to {w['end']}: {count} of the "
        f"{len(sig)} testable signals is confirmed and "
        f"{'none is contradicted' if not contradicted else str(len(contradicted)) + ' contradicted'}. "
        f"{len(early)} of the {len(sig)} were statistically significant before 2005, so this "
        f"is a premium that faded, not one that never existed. [FINDING src={METRICS}]"
    )


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def render(root: Path, tables: dict[str, pd.DataFrame], check: bool = False) -> bool:
    path = root / "README.md"
    text = path.read_text()
    new = fill(text, "headline", headline(root, tables))
    new = fill(fill(new, "survivorship", survivorship(tables)), "published", published(root))
    if check:
        return new == text
    path.write_text(new)
    return True
